#!/usr/bin/env python3
"""Write 3d/QFN-80-1EP_10x10mm_P0.4mm_EP3.4x3.4mm.wrl: a parametric 3D model
of the RP2354B's package for renders (KiCad's 3D library has no QFN-80 10x10).

RP2350 datasheet, QFN-80 package: 10 x 10 mm body, 0.85 mm high, 80 terminals
at 0.4 mm pitch (20 per side, 0.2 x 0.4 mm), 3.4 x 3.4 mm exposed pad,
pin 1 at the top of the left side (as the KiCad footprint).  Drawn as a matte
black moulded body, tinned terminals flush with its edges and underside, and a
pin-1 dimple.  KiCad VRML units are 0.1 in (2.54 mm).

Usage: python3 tools/make_qfn80_model.py
"""
import os

U = 1 / 2.54                      # mm -> VRML units
BODY, H, PITCH, N = 10.0, 0.85, 0.4, 20
TW, TL, TH = 0.2, 0.4, 0.2        # terminal width, length (in from the edge), visible height
EP = 3.4


def box(cx, cy, cz, sx, sy, sz, mat):
    return ('Transform { translation %.4f %.4f %.4f children [ Shape { appearance Appearance { '
            'material USE %s } geometry Box { size %.4f %.4f %.4f } } ] }\n'
            % (cx * U, cy * U, cz * U, mat, sx * U, sy * U, sz * U))


def cyl(cx, cy, cz, r, h, mat):
    return ('Transform { translation %.4f %.4f %.4f rotation 1 0 0 1.5708 children [ Shape { appearance '
            'Appearance { material USE %s } geometry Cylinder { radius %.4f height %.4f } } ] }\n'
            % (cx * U, cy * U, cz * U, mat, r * U, h * U))


out = ['#VRML V2.0 utf8\n',
       '# QFN-80-1EP 10x10 mm, 0.4 mm pitch, EP 3.4 mm (RP2354B / RP2350B) -- generated by tools/make_qfn80_model.py\n',
       'Shape { appearance Appearance { material DEF BODY Material { diffuseColor 0.08 0.08 0.09 '
       'specularColor 0.15 0.15 0.15 shininess 0.2 } } geometry Box { size 0 0 0 } }\n',
       'Shape { appearance Appearance { material DEF PIN Material { diffuseColor 0.78 0.78 0.80 '
       'specularColor 0.9 0.9 0.9 shininess 0.6 } } geometry Box { size 0 0 0 } }\n',
       'Shape { appearance Appearance { material DEF MARK Material { diffuseColor 0.25 0.25 0.27 } } '
       'geometry Box { size 0 0 0 } }\n']
# body, sitting on the board (z from 0.02 to H), a hair inside the terminals so they show
out.append(box(0, 0, (H + 0.02) / 2, BODY - 0.02, BODY - 0.02, H - 0.02, 'BODY'))
half = BODY / 2
first = (N - 1) * PITCH / 2
for i in range(N):
    t = -first + i * PITCH
    # left (pins 1-20 top to bottom), bottom (21-40 left to right), right (41-60 bottom to top), top (61-80)
    for (x, y, sx, sy) in ((-half + TL / 2, -t, TL, TW), (t, -half + TL / 2, TW, TL),
                           (half - TL / 2, t, TL, TW), (-t, half - TL / 2, TW, TL)):
        # VRML/KiCad 3D: +y is up the board (the footprint's -y)
        out.append(box(x, y, TH / 2, sx, sy, TH, 'PIN'))
out.append(box(0, 0, 0.01, EP, EP, 0.02, 'PIN'))
# pin-1 dimple near the corner of pin 1 (footprint: top of the left side = +y in 3D)
out.append(cyl(-half + 1.0, half - 1.0, H + 0.005, 0.35, 0.02, 'MARK'))
prj = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
fn = os.path.join(prj, '3d', 'QFN-80-1EP_10x10mm_P0.4mm_EP3.4x3.4mm.wrl')
open(fn, 'w').write(''.join(out))
print('wrote', os.path.relpath(fn, prj), '(%d terminals)' % (4 * N))
